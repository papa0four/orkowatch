// The recorded file is an excerpt, not the file as published. It is the first
// 1,002 lines of the file FIRST's address for the current scores served on
// 2026-11-24, epss_scores-2026-11-23.csv.gz: the comment line, the header,
// and the first 1,000 of its 411,399 rows, unchanged, compressed again with
// gzip. The whole file held 2,880,698 bytes and expanded to 12,525,840.
// EPSS scores are from FIRST, https://www.first.org/epss, generated by
// Empirical Security, and published free of charge.
const (
	recordedFile    = "testdata/epss_scores-2026-11-23-first-1000.csv.gz"
	recordedSHA256  = "5eaea6ea46c821bc07dade7beb1562f84ac607035c1db04f24891381cee9adff"
	recordedComment = "#model_version:v2026.06.15,score_date:2026-11-23T12:00:23Z\n"
	recordedHeader  = "cve,epss,percentile\n"
	recordedFirst   = "CVE-1999-0001,0.04753,0.921\n"
	recordedRows    = 1000
)

// recorded returns the recorded excerpt as it is held, and its text, having
// checked that it is still that file.
func recorded(t *testing.T) (compressed []byte, text string) {
	t.Helper()
	compressed, err := os.ReadFile(recordedFile)
	if err != nil {
		t.Fatal(err)
	}
	if sum := sha256.Sum256(compressed); hex.EncodeToString(sum[:]) != recordedSHA256 {
		t.Fatalf("the recorded excerpt hashes to %x, not what was recorded", sum)
	}
	z, err := gzip.NewReader(bytes.NewReader(compressed))
	if err != nil {
		t.Fatal(err)
	}
	data, err := io.ReadAll(z)
	if err != nil {
		t.Fatal(err)
	}
	return compressed, string(data)
}

// packed returns text compressed as the scores file is.
func packed(t *testing.T, text string) []byte {
	t.Helper()
	var out bytes.Buffer
	z := gzip.NewWriter(&out)
	if _, err := z.Write([]byte(text)); err != nil {
		t.Fatal(err)
	}
	if err := z.Close(); err != nil {
		t.Fatal(err)
	}
	return out.Bytes()
}

// changed returns text with the one occurrence of from replaced by to.
func changed(t *testing.T, text, from, to string) string {
	t.Helper()
	if n := strings.Count(text, from); n != 1 {
		t.Fatalf("%q occurs %d times in the recorded excerpt, want once", from, n)
	}
	return strings.Replace(text, from, to, 1)
}

// The excerpt of the file FIRST published is accepted, as held and packed
// again, and gives the score date and the model version of its comment line.
func TestCheckAcceptsTheRecordedExcerpt(t *testing.T) {
	compressed, text := recorded(t)
	if rows := strings.Count(text, "\n") - 2; rows != recordedRows {
		t.Fatalf("the recorded excerpt holds %d rows, want %d", rows, recordedRows)
	}
	for name, data := range map[string][]byte{"as held": compressed, "packed again": packed(t, text)} {
		facts, err := Scores{}.Check(bytes.NewReader(data))
		if err != nil {
			t.Fatalf("%s: the recorded excerpt was refused: %v", name, err)
		}
		if want := time.Date(2026, 11, 23, 12, 0, 23, 0, time.UTC); !facts.Date.Equal(want) || facts.Version != "v2026.06.15" {
			t.Errorf("%s: date %s and version %q, want %s and v2026.06.15", name, facts.Date, facts.Version, want)
		}
	}
}

// A score may be written with an exponent, as the file writes its smallest,
// and may be 0 or 1.
func TestCheckAcceptsEveryFormOfScore(t *testing.T) {
	_, text := recorded(t)
	for _, row := range []string{"CVE-1999-0001,1e-05,0.00021\n", "CVE-1999-0001,0,1\n", "CVE-1999-0001,1.0,0.0\n", "CVE-1999-0001,9.5e-06,0.5\n"} {
		if _, err := (Scores{}).Check(bytes.NewReader(packed(t, changed(t, text, recordedFirst, row)))); err != nil {
			t.Errorf("the row %q was refused: %v", row, err)
		}
	}
}

// Each way a file can fail to be the scores is refused, with the reason.
func TestCheckRefuses(t *testing.T) {
	compressed, text := recorded(t)
	row := func(to string) []byte { return packed(t, changed(t, text, recordedFirst, to)) }

	for _, tt := range []struct {
		name   string
		data   []byte
		reason string
	}{
		{"not gzip", []byte(text), "not a gzip file"},
		{"empty", nil, "not a gzip file"},
		{"nothing compressed", packed(t, ""), "it is empty"},
		{"cut short", compressed[:len(compressed)/2], "damaged or cut short"},
		{"cut short by its last bytes", compressed[:len(compressed)-4], "damaged or cut short"},
		{"a byte changed", flipped(compressed), "damaged or cut short"},
		{"bytes after the member", append(bytes.Clone(compressed), 'x'), "data follows the compressed scores"},
		{"a second member", append(bytes.Clone(compressed), compressed...), "data follows the compressed scores"},

		{"no comment line", packed(t, changed(t, text, recordedComment, "")), "its first line is not"},
		{"a comment with no date", packed(t, changed(t, text, ",score_date:2026-11-23T12:00:23Z", "")), "its first line is not"},
		{"a model version with an escape", packed(t, changed(t, text, "v2026.06.15", "v2026\x1b[2J")), "its model version"},
		{"no model version", packed(t, changed(t, text, "v2026.06.15", "")), "its model version"},
		{"a date that is not one", packed(t, changed(t, text, "2026-11-23T12:00:23Z", "yesterday")), "its score date"},
		{"no header", packed(t, changed(t, text, recordedHeader, "")), "its second line is not the header"},
		{"another header", packed(t, changed(t, text, recordedHeader, "cve,score,percentile\n")), "its second line is not the header"},
		{"no rows", packed(t, recordedComment+recordedHeader), "it holds no rows"},

		{"a row of two fields", row("CVE-1999-0001,0.04753\n"), "row 1 does not hold three fields"},
		{"a row of four fields", row("CVE-1999-0001,0.04753,0.921,0.5\n"), "row 1 does not hold three fields"},
		{"an empty row", row("\n"), "row 1 does not hold three fields"},
		{"a malformed CVE", row("CVE-99-1,0.04753,0.921\n"), "row 1 names \"CVE-99-1\""},
		{"a quoted CVE", row("\"CVE-1999-0001\",0.04753,0.921\n"), "which is not a CVE identifier"},
		{"a score above 1", row("CVE-1999-0001,1.04753,0.921\n"), "row 1 gives the score \"1.04753\""},
		{"a negative score", row("CVE-1999-0001,-0.04753,0.921\n"), "row 1 gives the score"},
		{"a score that is a word", row("CVE-1999-0001,NaN,0.921\n"), "row 1 gives the score"},
		{"a score in hexadecimal", row("CVE-1999-0001,0x1p-2,0.921\n"), "row 1 gives the score"},
		{"a percentile above 1", row("CVE-1999-0001,0.04753,2\n"), "row 1 gives the percentile \"2\""},
		{"a percentile left out", row("CVE-1999-0001,0.04753,\n"), "row 1 gives the percentile"},
		{"a carriage return", row("CVE-1999-0001,0.04753,0.921\r\n"), "row 1 gives the percentile"},
		{"a line too long", row("CVE-1999-0001,0.04753,0." + strings.Repeat("9", maxLine) + "\n"), "a line holds more than"},
	} {
		if _, err := (Scores{}).Check(bytes.NewReader(tt.data)); err == nil || !strings.Contains(err.Error(), tt.reason) {
			t.Errorf("%s: gave %v, want it refused for a reason naming %q", tt.name, err, tt.reason)
		}
	}
}

// flipped returns data with one bit of its compressed body changed.
func flipped(data []byte) []byte {
	out := bytes.Clone(data)
	out[len(out)/2] ^= 1
	return out
}

// Data that expands past the limit is refused, and data that expands to
// exactly the limit is not refused for its size.
func TestCheckStopsAtTheExpandedLimit(t *testing.T) {
	compressed, text := recorded(t)
	size := int64(len(text))
	if _, err := check(bytes.NewReader(compressed), size-1); err == nil || !strings.Contains(err.Error(), "it expands past") {
		t.Errorf("a limit one byte under the data gave %v, want it refused for its size", err)
	}
	if _, err := check(bytes.NewReader(compressed), size); err != nil {
		t.Errorf("a limit of exactly the data's size refused it: %v", err)
	}
	if size > maxExpanded {
		t.Errorf("the excerpt expands to %d bytes, more than the scores may", size)
	}
}

// The dataset names itself, applies everywhere, is fetched from the address
// FIRST gives with no other host to follow a redirect to, and states its
// terms.
func TestScoresStatesItsSource(t *testing.T) {
	var d dataset.Dataset = Scores{}
	origin := d.Origin()
	hosts, err := origin.Hosts()
	if err != nil || len(hosts) != 1 || hosts[0] != "epss.empiricalsecurity.com" {
		t.Errorf("hosts %q, %v; want FIRST's host for the file alone", hosts, err)
	}
	switch {
	case d.ID() != "epss" || !dataset.ValidID(d.ID()):
		t.Errorf("named %q", d.ID())
	case !d.AppliesTo(nil):
		t.Error("does not apply to a host")
	case origin.URL != "https://epss.empiricalsecurity.com/epss_scores-current.csv.gz":
		t.Errorf("fetched from %q", origin.URL)
	case !strings.Contains(origin.License, "No license stated") || !strings.Contains(origin.Attribution, "https://www.first.org/epss"):
		t.Errorf("terms %q; %q", origin.License, origin.Attribution)
	case d.MaxBytes() != 32<<20:
		t.Errorf("may hold %d bytes", d.MaxBytes())
	}
}
