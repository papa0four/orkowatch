// internal/dataset/epss/epss.go

// Package epss states FIRST's daily Exploit Prediction Scoring System scores
// as a dataset: where the file is published, the terms it comes under, and
// how a file is told from anything that is not the scores.
package epss

import (
	"bufio"
	"bytes"
	"compress/gzip"
	"errors"
	"fmt"
	"io"
	"regexp"
	"strconv"
	"strings"
	"time"

	"github.com/papa0four/orkowatch/internal/dataset"
	"github.com/papa0four/orkowatch/internal/osfingerprint"
)

const (
	// id names the scores in the store.
	id = "epss"

	// feed is the address FIRST's data page gives for the current day's
	// file. It redirects to that day's dated file on the same host.
	feed = "https://epss.empiricalsecurity.com/epss_scores-current.csv.gz"

	// maxBytes is the most the compressed file may hold, and maxExpanded
	// the most it may expand to. In late 2026 it held 2.7 MiB and expanded
	// to 11.9 MiB, a row for each of 411,399 CVEs, so both bounds leave
	// years of room and still refuse a file that is plainly something else.
	maxBytes    = 32 << 20
	maxExpanded = 128 << 20

	// maxLine is the most one line of the file may hold. A row is a CVE
	// identifier and two numbers.
	maxLine = 1 << 10

	// license and attribution are owatch's own statement of FIRST's terms.
	// FIRST publishes the scores free of charge and names no license, and
	// asks for attribution without giving its wording.
	license     = "No license stated; published free of charge by FIRST"
	attribution = "EPSS scores from FIRST, https://www.first.org/epss, generated by Empirical Security"

	// commentStart opens the file's first line, versionEnd parts the model
	// version from the score date in it, and header is the second line.
	commentStart = "#model_version:"
	versionEnd   = ",score_date:"
	header       = "cve,epss,percentile"

	// fieldSeparator parts the fields of a row. No field is quoted.
	fieldSeparator = ","

	// floatBits is the size of the float a score is read as.
	floatBits = 64
)

var (
	// modelVersion is what a model version may be written with. FIRST writes
	// one as a v and a date; the pattern admits what it may come to write
	// and nothing a terminal or a path would act on.
	modelVersion = regexp.MustCompile(`^[A-Za-z0-9._-]{1,64}$`)

	// probability is how the file writes a score or a percentile: decimal
	// digits, with a fraction or a negative exponent or both. It keeps out
	// what a float parser would also take, such as a sign, a hexadecimal
	// form, or a word for infinity.
	probability = regexp.MustCompile(`^[0-9]+(\.[0-9]+)?(e-[0-9]+)?$`)
)

// Scores is the daily EPSS scores file as a dataset.
type Scores struct{}

// ID names the scores.
func (Scores) ID() string { return id }

// AppliesTo reports true: the scores cover CVEs in the software of every
// system owatch runs on.
func (Scores) AppliesTo(*osfingerprint.OSInfo) bool { return true }

// MaxBytes is the most the compressed file may hold.
func (Scores) MaxBytes() int64 { return maxBytes }

// Origin is the address FIRST gives for the current file, which redirects
// only within its own host, and owatch's statement of FIRST's terms.
func (Scores) Origin() dataset.Origin {
	return dataset.Origin{URL: feed, License: license, Attribution: attribution}
}

// Check refuses data that is not the scores file whole: one gzip member and
// nothing after it, expanding within the limit to the comment line that gives
// the model version and the score date, the header, and at least one row,
// every row a CVE identifier with a score and a percentile from 0 to 1. A
// file cut short fails gzip's own length and checksum. It gives the score
// date as the data's date and the model version as its version. The scores
// are the same for every host, so the host is not consulted.
func (Scores) Check(data io.Reader, _ *osfingerprint.OSInfo) (dataset.Facts, error) {
	return check(data, maxExpanded)
}

// check is Check with the most the data may expand to given, so a test can
// reach the limit without a file of that size.
func check(data io.Reader, limit int64) (dataset.Facts, error) {
	// gzip reads a byte at a time from a reader that allows it, so nothing
	// past the member's end is taken from compressed.
	compressed := bufio.NewReader(data)
	expanded, err := gzip.NewReader(compressed)
	if err != nil {
		return dataset.Facts{}, fmt.Errorf("not a gzip file: %w", err)
	}
	expanded.Multistream(false)

	// One byte more than the limit is allowed through, so an allowance that
	// ran out is data past the limit and not data that ends on it.
	allowed := &io.LimitedReader{R: expanded, N: limit + 1}
	lines := bufio.NewScanner(allowed)
	lines.Buffer(make([]byte, 0, maxLine), maxLine)
	lines.Split(splitLines)

	facts, err := readScores(lines)
	damage := lines.Err()
	if err != nil && damage == nil {
		// A line that is not the scores' may be what damaged data expanded
		// to. Reading on to the end lets gzip judge its length and checksum,
		// so a download that was corrupted is called that and not a bad row.
		_, damage = io.Copy(io.Discard, allowed)
	}
	switch {
	case allowed.N == 0:
		return dataset.Facts{}, fmt.Errorf("it expands past the %d MiB the scores may hold", limit>>20)
	case errors.Is(damage, bufio.ErrTooLong):
		return dataset.Facts{}, fmt.Errorf("a line holds more than %d bytes", maxLine)
	case damage != nil:
		return dataset.Facts{}, fmt.Errorf("the compressed data is damaged or cut short: %w", damage)
	case err != nil:
		return dataset.Facts{}, err
	}
	if _, err := compressed.ReadByte(); !errors.Is(err, io.EOF) {
		return dataset.Facts{}, errors.New("data follows the compressed scores")
	}
	return facts, nil
}

// splitLines parts lines at a line feed and nowhere else. The file ends its
// lines with one, and bufio.ScanLines would also take, and hide, a carriage
// return before it.
func splitLines(data []byte, atEOF bool) (advance int, line []byte, err error) {
	if end := bytes.IndexByte(data, '\n'); end >= 0 {
		return end + 1, data[:end], nil
	}
	if atEOF && len(data) > 0 {
		return len(data), data, nil
	}
	return 0, nil, nil
}

// readScores reads the comment line, the header, and every row from lines. It
// stops at the first line that is not what the file holds there; a read that
// failed ends the lines early and is the caller's to report from lines.Err.
func readScores(lines *bufio.Scanner) (dataset.Facts, error) {
	if !lines.Scan() {
		return dataset.Facts{}, errors.New("it is empty")
	}
	facts, err := readComment(lines.Text())
	if err != nil {
		return dataset.Facts{}, err
	}
	if !lines.Scan() || lines.Text() != header {
		return dataset.Facts{}, fmt.Errorf("its second line is not the header %q", header)
	}

	rows := 0
	for lines.Scan() {
		rows++
		if err := checkRow(lines.Text()); err != nil {
			return dataset.Facts{}, fmt.Errorf("row %d %w", rows, err)
		}
	}
	if rows == 0 {
		return dataset.Facts{}, errors.New("it holds no rows")
	}
	return facts, nil
}

// readComment reads the model version and the score date from the file's
// first line.
func readComment(line string) (dataset.Facts, error) {
	rest, found := strings.CutPrefix(line, commentStart)
	version, date, parted := strings.Cut(rest, versionEnd)
	if !found || !parted {
		return dataset.Facts{}, fmt.Errorf("its first line is not %s<version>%s<date and time>", commentStart, versionEnd)
	}
	if !modelVersion.MatchString(version) {
		return dataset.Facts{}, fmt.Errorf("its model version %q is not one", version)
	}
	scored, err := time.Parse(time.RFC3339, date)
	if err != nil {
		return dataset.Facts{}, fmt.Errorf("its score date %q is not a date and time", date)
	}
	return dataset.Facts{Date: scored, Version: version}, nil
}

// checkRow refuses a row that is not a CVE identifier, a score, and a
// percentile. The error completes "row N".
func checkRow(row string) error {
	cve, rest, _ := strings.Cut(row, fieldSeparator)
	score, percentile, parted := strings.Cut(rest, fieldSeparator)
	switch {
	case !parted || strings.Contains(percentile, fieldSeparator):
		return errors.New("does not hold three fields")
	case !dataset.ValidCVE(cve):
		return fmt.Errorf("names %q, which is not a CVE identifier", cve)
	case !isProbability(score):
		return fmt.Errorf("gives the score %q, which is not a number from 0 to 1", score)
	case !isProbability(percentile):
		return fmt.Errorf("gives the percentile %q, which is not a number from 0 to 1", percentile)
	}
	return nil
}

// isProbability reports whether s is a number from 0 to 1 as the file writes
// one.
func isProbability(s string) bool {
	if !probability.MatchString(s) {
		return false
	}
	v, err := strconv.ParseFloat(s, floatBits)
	return err == nil && v >= 0 && v <= 1
}
